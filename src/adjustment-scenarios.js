const assumptions =
  "Treat the graph as complete. Target the total effect of A on Y. All variables except dashed U are measured accurately; consistency, no interference and treatment positivity hold. Assume correctly specified estimation when comparing adjustment sets.";
function scenario(
  id,
  title,
  context,
  nodes,
  edges,
  explanation,
  lesson,
  action,
) {
  return {
    id,
    title,
    context: `${context} Treat the graph as complete.`,
    graph: {
      nodes: nodes.map(([id, , x, y]) => [id, x, y]),
      edges: edges.map(([a, b]) => [a, b]),
      description: edges.map(([a, b]) => `${a} causes ${b}`).join("; ") + ".",
    },
    facts: nodes.map(([id, label]) => [id, label]),
    weights: edges.map(([, , weight]) => weight),
    unmeasured: nodes.filter(([id]) => id === "U").map(([id]) => id),
    explanation,
    lesson,
    action,
    assumptions,
    sources,
    adjustment: true,
    prompt: "Select a valid adjustment set for the total effect of A on Y.",
  };
}
